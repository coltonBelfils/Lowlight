package manifest

import (
	"fmt"
	"os"
	"sort"
	"strings"
)

const CurrentLockVersion = 1

// LockPackage represents one `[[package]]` entry in `lowlight.lock` (`SPECIFICATION.md §12.3`).
type LockPackage struct {
	Name         string
	Version      string
	Index        string
	URL          string
	Hash         string
	Path         string
	Dependencies []string
}

// Lockfile represents a deterministic `lowlight.lock`.
type Lockfile struct {
	LockVersion int
	Packages    []LockPackage
}

// LoadLockfile reads and parses `lowlight.lock` from disk.
func LoadLockfile(path string) (*Lockfile, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return ParseLockfile(path, string(raw))
}

// ParseLockfile parses a `lowlight.lock` TOML document.
func ParseLockfile(path, raw string) (*Lockfile, error) {
	tbl, err := ParseTOML(raw)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	ver := int(getInt(tbl, "lock_version"))
	if ver == 0 {
		ver = CurrentLockVersion
	}
	if ver != CurrentLockVersion {
		return nil, fmt.Errorf("%s: unsupported lock_version %d (expected %d)", path, ver, CurrentLockVersion)
	}
	lf := &Lockfile{LockVersion: ver}
	if pkgsRaw, ok := tbl["package"]; ok {
		arr, ok := pkgsRaw.([]TOMLTable)
		if !ok {
			return nil, fmt.Errorf("%s: [[package]] must be an array of tables", path)
		}
		for _, pt := range arr {
			lp := LockPackage{
				Name:         getString(pt, "name"),
				Version:      getString(pt, "version"),
				Index:        getString(pt, "index"),
				URL:          getString(pt, "url"),
				Hash:         getString(pt, "hash"),
				Path:         getString(pt, "path"),
				Dependencies: getStringSlice(pt, "dependencies"),
			}
			if lp.Name == "" {
				return nil, fmt.Errorf("%s: [[package]] entry missing `name`", path)
			}
			if lp.URL != "" && !IsValidSHA256Hash(lp.Hash) {
				return nil, fmt.Errorf("%s: locked package %q missing valid sha256 `hash`", path, lp.Name)
			}
			sort.Strings(lp.Dependencies)
			lf.Packages = append(lf.Packages, lp)
		}
	}
	lf.Sort()
	return lf, nil
}

// Sort canonically orders `Packages` by `(Name, Version, URL)` and sorts each `Dependencies` list.
func (lf *Lockfile) Sort() {
	for i := range lf.Packages {
		sort.Strings(lf.Packages[i].Dependencies)
	}
	sort.Slice(lf.Packages, func(i, j int) bool {
		a, b := lf.Packages[i], lf.Packages[j]
		if a.Name != b.Name {
			return a.Name < b.Name
		}
		if a.Version != b.Version {
			return a.Version < b.Version
		}
		return a.URL < b.URL
	})
}

// FindByName looks up the single locked package matching `name`.
func (lf *Lockfile) FindByName(name string) (LockPackage, bool) {
	if lf == nil {
		return LockPackage{}, false
	}
	for _, p := range lf.Packages {
		if p.Name == name {
			return p, true
		}
	}
	return LockPackage{}, false
}

// Format renders `lowlight.lock` in deterministic TOML format (`SPECIFICATION.md §12.3`).
func (lf *Lockfile) Format() string {
	lf.Sort()
	var sb strings.Builder
	sb.WriteString("# Code generated by `lowlight`; DO NOT EDIT.\n")
	ver := lf.LockVersion
	if ver == 0 {
		ver = CurrentLockVersion
	}
	fmt.Fprintf(&sb, "lock_version = %d\n", ver)
	for _, p := range lf.Packages {
		sb.WriteString("\n[[package]]\n")
		fmt.Fprintf(&sb, "name = %s\n", FormatTOMLString(p.Name))
		v := p.Version
		if v == "" {
			v = "0.0.0"
		}
		fmt.Fprintf(&sb, "version = %s\n", FormatTOMLString(v))
		if p.Index != "" {
			fmt.Fprintf(&sb, "index = %s\n", FormatTOMLString(p.Index))
		}
		if p.URL != "" {
			fmt.Fprintf(&sb, "url = %s\n", FormatTOMLString(p.URL))
		}
		if p.Hash != "" {
			fmt.Fprintf(&sb, "hash = %s\n", FormatTOMLString(p.Hash))
		}
		if p.Path != "" {
			fmt.Fprintf(&sb, "path = %s\n", FormatTOMLString(p.Path))
		}
		if len(p.Dependencies) > 0 {
			fmt.Fprintf(&sb, "dependencies = %s\n", FormatTOMLStringArray(p.Dependencies))
		}
	}
	return sb.String()
}

// WriteLockfile atomically writes a deterministic `lowlight.lock`.
func WriteLockfile(path string, lf *Lockfile) error {
	return os.WriteFile(path, []byte(lf.Format()), 0o644)
}

// IndexVersion represents one `[versions."<semver>"]` release entry in a decentralized static index (`SPECIFICATION.md §12.4`).
type IndexVersion struct {
	Version      SemVer
	URL          string
	Hash         string
	Edition      string
	Yanked       bool
	Dependencies map[string]DepSpec
	Targets      map[string]TargetConfig
}

// StaticIndex represents a decoded decentralized static package index (`<pkg>.toml`).
type StaticIndex struct {
	Name        string
	Description string
	License     string
	Repository  string
	Deprecated  string
	Versions    map[string]IndexVersion
}

// ParseStaticIndex parses and validates a static TOML package index (`SPECIFICATION.md §12.4`).
func ParseStaticIndex(source, raw string) (*StaticIndex, error) {
	tbl, err := ParseTOML(raw)
	if err != nil {
		return nil, fmt.Errorf("index %s: %w", source, err)
	}
	idx := &StaticIndex{
		Versions: make(map[string]IndexVersion),
	}
	if pkgRaw, ok := tbl["package"]; ok {
		pt, ok := pkgRaw.(TOMLTable)
		if !ok {
			return nil, fmt.Errorf("index %s: [package] must be a table", source)
		}
		idx.Name = getString(pt, "name")
		idx.Description = getString(pt, "description")
		idx.License = getString(pt, "license")
		idx.Repository = getString(pt, "repository")
		idx.Deprecated = getString(pt, "deprecated")
	}
	versRaw, ok := tbl["versions"]
	if !ok {
		return nil, fmt.Errorf("index %s: missing [versions] table", source)
	}
	versTbl, ok := versRaw.(TOMLTable)
	if !ok {
		return nil, fmt.Errorf("index %s: [versions] must be a table", source)
	}
	for verStr, vr := range versTbl {
		vt, ok := vr.(TOMLTable)
		if !ok {
			return nil, fmt.Errorf("index %s: [versions.%q] must be a table", source, verStr)
		}
		sv, err := ParseSemVer(verStr)
		if err != nil {
			return nil, fmt.Errorf("index %s: invalid version key %q: %w", source, verStr, err)
		}
		urlVal := getString(vt, "url")
		hashVal := getString(vt, "hash")
		if urlVal == "" {
			return nil, fmt.Errorf("index %s: version %q missing `url`", source, verStr)
		}
		if !IsValidSHA256Hash(hashVal) {
			return nil, fmt.Errorf("index %s: version %q missing valid sha256 `hash`", source, verStr)
		}
		iv := IndexVersion{
			Version:      sv,
			URL:          urlVal,
			Hash:         hashVal,
			Edition:      getString(vt, "edition"),
			Yanked:       getBool(vt, "yanked"),
			Dependencies: make(map[string]DepSpec),
			Targets:      make(map[string]TargetConfig),
		}
		if err := parseDepTable(source, vt, "dependencies", iv.Dependencies, false); err != nil {
			return nil, err
		}
		if tgtRaw, ok := vt["target"]; ok {
			if tt, ok := tgtRaw.(TOMLTable); ok {
				for sel, tv := range tt {
					if sub, ok := tv.(TOMLTable); ok {
						tc := TargetConfig{
							Dependencies:    make(map[string]DepSpec),
							DevDependencies: make(map[string]DepSpec),
						}
						if err := parseDepTable(source, sub, "dependencies", tc.Dependencies, false); err != nil {
							return nil, err
						}
						iv.Targets[sel] = tc
					}
				}
			}
		}
		idx.Versions[sv.String()] = iv
	}
	return idx, nil
}

// EffectiveDeps returns dependencies for this version merged with matching `[versions."...".target.<sel>.dependencies]`.
func (iv IndexVersion) EffectiveDeps(target TargetInfo) map[string]DepSpec {
	out := make(map[string]DepSpec, len(iv.Dependencies))
	for k, v := range iv.Dependencies {
		out[k] = v
	}
	selectors := make([]string, 0, len(iv.Targets))
	for sel := range iv.Targets {
		selectors = append(selectors, sel)
	}
	SortTargetSelectors(selectors)
	for _, sel := range selectors {
		if !target.MatchesSelector(sel) {
			continue
		}
		for k, v := range iv.Targets[sel].Dependencies {
			out[k] = v
		}
	}
	return out
}

// SelectMinimalVersion performs Minimal Version Selection (MVS) across all constraints:
// picks the smallest non-yanked version satisfying every constraint (`SPECIFICATION.md §12.5`).
func (idx *StaticIndex) SelectMinimalVersion(constraints []VersionConstraint, allowYankedVersion string) (IndexVersion, bool) {
	var cands []IndexVersion
	for _, iv := range idx.Versions {
		if iv.Yanked && iv.Version.String() != allowYankedVersion {
			continue
		}
		ok := true
		for _, c := range constraints {
			if !c.Matches(iv.Version) {
				ok = false
				break
			}
		}
		if ok {
			cands = append(cands, iv)
		}
	}
	if len(cands) == 0 {
		return IndexVersion{}, false
	}
	sort.Slice(cands, func(i, j int) bool {
		return cands[i].Version.Compare(cands[j].Version) < 0
	})
	return cands[0], true
}
