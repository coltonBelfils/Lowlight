// WebsiteConfig configures BuildWebsite.
type WebsiteConfig struct {
	Root   string // repository root
	OutDir string
}

// BuildWebsite assembles and writes the complete Lowlight website.
func BuildWebsite(cfg WebsiteConfig) (*Site, []Problem, error) {
	s := &Site{
		Title:    "Lowlight",
		Tagline:  "Lowlight is a systems language with C-level control, deterministic memory, and no null, garbage collector, or lifetime annotations.",
		Sections: WebsiteSections,
		Root:     cfg.Root,
		Footer:   `Lowlight is open source. These pages are generated by <code>go run ./cmd/lowlight-site</code> from the repository: the specification, conventions, implementation guide, package documentation, and examples are always current with the compiler.`,
	}
	content := filepath.Join(cfg.Root, "website", "content")
	if err := s.addContentDir(content, cfg.Root); err != nil {
		return nil, nil, err
	}
	if err := s.addSpecification(cfg.Root); err != nil {
		return nil, nil, err
	}
	if err := s.addRootDoc(cfg.Root, "CONVENTIONS.md", &Page{Section: "guides", Group: "Writing Lowlight", Path: "guides/effective-lowlight.html", Title: "Effective Lowlight", NavTitle: "Effective Lowlight (conventions)", Order: 5, Summary: "The official style guide: naming, formatting, failure handling, and idioms."}); err != nil {
		return nil, nil, err
	}
	if err := s.addImplementationGuide(cfg.Root); err != nil {
		return nil, nil, err
	}
	if err := s.addRootDoc(cfg.Root, "VERSION_HISTORY.md", &Page{Section: "about", Path: "about/history.html", Title: "Version history", Order: 20, Summary: "How the language and toolchain have changed, release by release."}); err != nil {
		return nil, nil, err
	}
	examples, err := LoadExamples(filepath.Join(cfg.Root, "website", "examples"))
	if err != nil {
		return nil, nil, err
	}
	s.addExamplePages(examples, "examples")
	s.AddPage(&Page{Section: "examples", Path: "examples/index.html", Title: "Lowlight by Example", Order: 0, Body: examplesIndexBody(examples), Layout: "wide",
		Summary: "Annotated, runnable programs that each demonstrate one feature."})

	if err := s.addStdlib(cfg.Root); err != nil {
		return nil, nil, err
	}
	probs, err := s.Build(cfg.OutDir)
	return s, probs, err
}

// addContentDir adds every Markdown file under dir. A file's section is its first
// directory; front matter supplies title, nav, group, order, summary, and layout.
func (s *Site) addContentDir(dir, root string) error {
	return filepath.WalkDir(dir, func(fp string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(fp, ".md") {
			return nil
		}
		b, err := os.ReadFile(fp)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, fp)
		rel = filepath.ToSlash(rel)
		meta, _ := markdown.SplitFrontMatter(string(b))
		sec := "start"
		if i := strings.IndexByte(rel, '/'); i > 0 {
			sec = rel[:i]
		}
		order, _ := strconv.ParseFloat(meta["order"], 64)
		repoRel, _ := filepath.Rel(root, fp)
		p := &Page{
			Section:  sec,
			Group:    meta["group"],
			Path:     strings.TrimSuffix(rel, ".md") + ".html",
			Title:    meta["title"],
			NavTitle: meta["nav"],
			Summary:  meta["summary"],
			Order:    order,
			Layout:   meta["layout"],
			Hidden:   meta["hidden"] == "true",
			Markdown: string(b),
			DocKey:   filepath.ToSlash(repoRel),
			SrcDir:   path.Dir(filepath.ToSlash(repoRel)),
		}
		if rel == "index.md" {
			p.Layout = "home"
			p.Section = ""
		}
		s.AddPage(p)
		return nil
	})
}

// addRootDoc adds a single repository Markdown file as one page.
func (s *Site) addRootDoc(root, name string, p *Page) error {
	b, err := os.ReadFile(filepath.Join(root, name))
	if err != nil {
		return err
	}
	p.Markdown = string(b)
	p.DocKey = name
	p.SrcDir = "."
	s.AddPage(p)
	return nil
}

var reChapter = regexp.MustCompile(`^(\d+)\.\s+(.*)$`)

func pageSlug(title string) string {
	t := title
	if m := reChapter.FindStringSubmatch(t); m != nil {
		t = m[2]
	}
	if strings.HasPrefix(t, "Part ") {
		if i := strings.Index(t, ": "); i > 0 {
			t = t[i+2:]
		}
	}
	return markdown.Slug(strings.ReplaceAll(t, ",", ""))
}

// addSpecification splits SPECIFICATION.md into one page per part, chapter, and appendix.
func (s *Site) addSpecification(root string) error {
	b, err := os.ReadFile(filepath.Join(root, "SPECIFICATION.md"))
	if err != nil {
		return err
	}
	inChapters := false
	chunks := SplitMarkdown(string(b), func(level int, title string) bool {
		if level == 1 {
			inChapters = strings.HasPrefix(title, "Part III") || strings.HasPrefix(title, "Part IV") || title == "Appendices"
			return true
		}
		return level == 2 && inChapters && (reChapter.MatchString(title) || strings.HasPrefix(title, "Appendix "))
	})
	group := ""
	order := 100.0
	for i, c := range chunks {
		body := strings.TrimSpace(c.Markdown)
		// Drop bare part headings that only introduce their chapters.
		if c.Level == 1 && i > 0 && strings.Count(body, "\n") == 0 {
			group = strings.TrimPrefix(c.Title, "Part ")
			group = groupName(c.Title)
			// Map the part's anchor onto the next chunk by prepending an invisible target.
			if i+1 < len(chunks) {
				chunks[i+1].Markdown = fmt.Sprintf("<span id=\"%s\"></span>\n\n", markdown.Slug(c.Title)) + chunks[i+1].Markdown
			}
			continue
		}
		p := &Page{Section: "ref", DocKey: "SPECIFICATION.md", SrcDir: ".", Markdown: c.Markdown, Order: order}
		order++
		switch {
		case i == 0:
			p.Path, p.Title, p.NavTitle, p.Group, p.Order = "spec/index.html", "The Lowlight Language Specification", "Overview and contents", "Specification", 50
			p.Summary = "The complete definition of the Lowlight language."
		case c.Level == 1:
			group = groupName(c.Title)
			p.Path, p.Title, p.Group = "spec/"+pageSlug(c.Title)+".html", strings.TrimSpace(c.Title[strings.Index(c.Title, ":")+1:]), group
			if strings.HasPrefix(c.Title, "Part IV") {
				p.NavTitle = "About this part"
			}
		default:
			p.Path, p.Title, p.Group = "spec/"+pageSlug(c.Title)+".html", c.Title, group
		}
		if p.Title == "" {
			p.Title = c.Title
		}
		s.AddPage(p)
	}
	return nil
}

func groupName(partTitle string) string {
	switch {
	case strings.HasPrefix(partTitle, "Part I:"), strings.HasPrefix(partTitle, "Part II:"):
		return "Specification"
	case strings.HasPrefix(partTitle, "Part III"):
		return "Language reference"
	case strings.HasPrefix(partTitle, "Part IV"):
		return "Implementer's guide"
	case partTitle == "Appendices":
		return "Appendices"
	}
	return partTitle
}

// addImplementationGuide splits IMPLEMENTATION.md at its numbered sections.
func (s *Site) addImplementationGuide(root string) error {
	b, err := os.ReadFile(filepath.Join(root, "IMPLEMENTATION.md"))
	if err != nil {
		return err
	}
	chunks := SplitMarkdown(string(b), func(level int, title string) bool {
		return level == 2 && reChapter.MatchString(title)
	})
	for i, c := range chunks {
		p := &Page{Section: "internals", Group: "Compiler implementation", DocKey: "IMPLEMENTATION.md", SrcDir: ".", Markdown: c.Markdown, Order: 10 + float64(i)}
		if i == 0 {
			p.Path, p.Title, p.Group, p.Order = "internals/index.html", "Lowlight internals", "", 0
			p.NavTitle = "Overview"
			p.Summary = "How the Lowlight compiler, runtime, and tools are built."
		} else {
			p.Path, p.Title = "internals/"+pageSlug(c.Title)+".html", c.Title
			if m := reChapter.FindStringSubmatch(c.Title); m != nil {
				p.NavTitle = m[2]
			}
		}
		s.AddPage(p)
	}
	return nil
}

// addStdlib documents every package under std/.
func (s *Site) addStdlib(root string) error {
	ld, err := docgen.Load([]string{filepath.Join(root, "std")}, root)
	if err != nil {
		return err
	}
	opts := APIOptions{
		Loaded:  ld,
		Section: "std",
		Group:   "Standard library",
		Order:   10,
		PagePath: func(dir string) string {
			return "std/" + strings.ReplaceAll(strings.TrimPrefix(dir, "std/"), "/", "-") + ".html"
		},
		ImportPath: func(dir string) string { return dir },
		SourceDir:  "std/src",
	}
	pkgs := BuildPackages(opts)
	AddAPIPages(s, pkgs, opts)
	idx := ld.Index
	s.ResolveRef = func(target string) (string, string, bool) {
		e, _ := idx.ResolveLink(target, "", "")
		if e == nil || !strings.HasPrefix(e.HTMLHref, "std/") {
			return "", "", false
		}
		return e.HTMLHref, e.Signature, true
	}
	intro := `# Standard library

The standard library is a set of ordinary Lowlight packages under ` + "`std/`" + `. Import one by path and use its exported names through the last path segment:

` + "```lowlight\nimport \"std/fs\"\n\nbind main = fn(): {\n\tlet text = fs.read_text(\"notes.txt\") ?? \"\"\n\tprintln(text.len())\n}\n```" + `

` + "`std/core`" + ` is the **prelude**: it is imported into every file automatically, unqualified, and defines the collection types, ` + "`Result`" + ` and ` + "`Error`" + `, the methods on primitive types, and the interfaces behind operators and loops. See [the prelude chapter of the specification](/spec/the-prelude.html) for how the language relies on it.

Every page below is generated from the doc comments in the source, so it is always current. Each declaration links to its source.

## Packages
`
	s.AddPage(&Page{Section: "std", Path: "std/index.html", Title: "Standard library", NavTitle: "Overview", Order: 0, Markdown: intro + "\n<div id=\"pkg-table\"></div>\n", DocKey: "page:std/index.html", SrcDir: "."})
	// The package table is appended after rendering.
	s.postRender = append(s.postRender, func() {
		for _, p := range s.Pages {
			if p.Path == "std/index.html" {
				p.Body = strings.Replace(p.Body, `<div id="pkg-table"></div>`, PackageIndexBody(p.Path, pkgs), 1)
			}
		}
	})
	return nil
}
