package site

import (
	"os"
	"path/filepath"
	"strings"

	"lowlight/internal/docgen"
	"lowlight/internal/manifest"
)

// APIDocsConfig configures BuildAPIDocs.
type APIDocsConfig struct {
	Loaded *docgen.Loaded
	OutDir string
	Title  string // project name; defaults to the manifest's package name or the root directory
}

// BuildAPIDocs writes package documentation for a Lowlight project: an index of its
// packages, one page per package, and highlighted source pages. It is what
// `lowlight doc` produces.
func BuildAPIDocs(cfg APIDocsConfig) (*Site, []Problem, error) {
	ld := cfg.Loaded
	name := cfg.Title
	if name == "" {
		name = projectName(ld.RootDir)
	}
	s := &Site{
		Title:    name,
		Tagline:  "Package documentation for " + name + ".",
		Sections: []Section{{ID: "pkg", Title: "Packages", Index: "index.html", InNav: true}},
		Root:     ld.RootDir,
		Footer:   "Generated by <code>lowlight doc</code>.",
	}
	importPath := func(dir string) string {
		if dir == "." || dir == "" {
			return name
		}
		if strings.HasPrefix(dir, "std/") || dir == "std" {
			return dir
		}
		return name + "/" + dir
	}
	opts := APIOptions{
		Loaded:     ld,
		Section:    "pkg",
		Order:      10,
		ImportPath: importPath,
		PagePath: func(dir string) string {
			if dir == "." || dir == "" {
				return "pkg/" + slugify(name) + ".html"
			}
			return "pkg/" + strings.ReplaceAll(dir, "/", "-") + ".html"
		},
		SourceDir: "src",
	}
	pkgs := BuildPackages(opts)
	AddAPIPages(s, pkgs, opts)
	idx := ld.Index
	s.ResolveRef = func(target string) (string, string, bool) {
		e, _ := idx.ResolveLink(target, "", "")
		if e == nil || !strings.HasSuffix(strings.SplitN(e.HTMLHref, "#", 2)[0], ".html") {
			return "", "", false
		}
		return e.HTMLHref, e.Signature, true
	}
	index := &Page{Section: "pkg", Path: "index.html", Title: name, NavTitle: "All packages", Order: 0, Layout: "wide",
		Body: `<h1 id="top">` + escapeHTML(name) + `</h1><p>Packages in this project. Every page is generated from doc comments; each declaration links to its source.</p>` + PackageIndexBody("index.html", pkgs)}
	s.AddPage(index)
	probs, err := s.Build(cfg.OutDir)
	return s, probs, err
}

func escapeHTML(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

func slugify(s string) string {
	s = strings.ToLower(s)
	var b strings.Builder
	for _, r := range s {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '-' || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteByte('-')
		}
	}
	if b.Len() == 0 {
		return "package"
	}
	return b.String()
}

func projectName(root string) string {
	if root == "" {
		return "Lowlight project"
	}
	if b, err := os.ReadFile(filepath.Join(root, manifest.ManifestFilename)); err == nil {
		inPkg := false
		for _, ln := range strings.Split(string(b), "\n") {
			t := strings.TrimSpace(ln)
			if strings.HasPrefix(t, "[") {
				inPkg = t == "[package]"
				continue
			}
			if inPkg && strings.HasPrefix(t, "name") {
				if _, v, ok := strings.Cut(t, "="); ok {
					return strings.Trim(strings.TrimSpace(v), `"`)
				}
			}
		}
	}
	return filepath.Base(root)
}
