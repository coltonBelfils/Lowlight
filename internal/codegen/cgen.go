func (g *cEmitter) cmpInlineExpr(t types.Type, a, b string) string {
	if customCmp := g.prog.Checked.LookupConcreteMethod(t, "cmp"); customCmp != nil {
		return fmt.Sprintf("%s(%s, %s)", customCmp.CName, a, b)
	}
	if p, isPrim := t.(*types.Primitive); isPrim {
		if p.Kind == types.PrimString {
			if cmpM := g.prog.Checked.LookupConcreteMethod(types.TypeString, "cmp"); cmpM != nil {
				return fmt.Sprintf("%s(%s, %s)", cmpM.CName, a, b)
			}
		}
		return fmt.Sprintf("(((%s) < (%s)) ? -1LL : (((%s) > (%s)) ? 1LL : 0LL))", a, b, a, b)
	}
	switch v := t.(type) {
	case *types.Distinct:
		if isCScalarType(v.Base) {
			return g.cmpInlineExpr(v.Base, fmt.Sprintf("(%s)(%s)", CType(v.Base), a), fmt.Sprintf("(%s)(%s)", CType(v.Base), b))
		}
		return g.cmpInlineExpr(v.Base, a, b)
	case *types.Enum:
		if !v.IsTagged {
			return fmt.Sprintf("(((%s) < (%s)) ? -1LL : (((%s) > (%s)) ? 1LL : 0LL))", a, b, a, b)
		}
	}
	panic(fmt.Sprintf("ICE: no C cmp implementation for %s", t.String()))
}

func (g *cEmitter) copyExpr(t types.Type) string {
	if custom := g.prog.Checked.LookupConcreteMethod(t, "copy"); custom != nil {
		return custom.CName
	}
	if t.IsPlain() {
		return ""
	}
	switch v := t.(type) {
	case *types.Primitive:
		if v.Kind == types.PrimString {
			return "ll_copy__string"
		}
	case *types.Vector, *types.StackArray, *types.Distinct, *types.Interface, *types.Func:
		if fn, isFn := v.(*types.Func); isFn && !fn.Closure {
			return ""
		}
		if ifc, isIfc := v.(*types.Interface); isIfc && ifc.UsesSelf {
			panic(fmt.Sprintf("ICE: cannot copy Self-using interface %s", t.String()))
		}
		return ir.CopyFnName(t)
	}
	panic(fmt.Sprintf("ICE: no C copy implementation for %s", t.String()))
}

func (g *cEmitter) eqInlineExpr(t types.Type, a, b string) string {
	if p, isPrim := t.(*types.Primitive); isPrim && p.Kind != types.PrimString {
		return fmt.Sprintf("((%s) == (%s))", a, b)
	}
	if custom := g.prog.Checked.LookupConcreteMethod(t, "eq"); custom != nil {
		return fmt.Sprintf("%s(%s, %s)", custom.CName, a, b)
	}
	if customCmp := g.prog.Checked.LookupConcreteMethod(t, "cmp"); customCmp != nil {
		return fmt.Sprintf("(%s(%s, %s) == 0)", customCmp.CName, a, b)
	}
	switch v := t.(type) {
	case *types.Primitive:
		if v.Kind == types.PrimString {
			if eqM := g.prog.Checked.LookupConcreteMethod(types.TypeString, "eq"); eqM != nil {
				return fmt.Sprintf("%s(%s, %s)", eqM.CName, a, b)
			}
		}
		return fmt.Sprintf("((%s) == (%s))", a, b)
	case *types.Enum:
		if !v.IsTagged {
			return fmt.Sprintf("((%s) == (%s))", a, b)
		}
	case *types.Ptr, *types.Ref:
		return fmt.Sprintf("((%s) == (%s))", a, b)
	case *types.Distinct:
		if isCScalarType(v.Base) {
			cBase := CType(v.Base)
			return g.eqInlineExpr(v.Base, fmt.Sprintf("((%s)(%s))", cBase, a), fmt.Sprintf("((%s)(%s))", cBase, b))
		}
		return g.eqInlineExpr(v.Base, a, b)
	}
	panic(fmt.Sprintf("ICE: no C eq implementation for %s", t.String()))
}

func (g *cEmitter) hashInlineExpr(t types.Type, expr string) string {
	if custom := g.prog.Checked.LookupConcreteMethod(t, "hash"); custom != nil {
		return fmt.Sprintf("%s(%s)", custom.CName, expr)
	}
	switch v := t.(type) {
	case *types.Distinct:
		return fmt.Sprintf("%s(%s)", ir.HashFnName(v), expr)
	case *types.Enum:
		if !v.IsTagged {
			return fmt.Sprintf("%s((uint64_t)(%s))", g.hashMixFnName(), expr)
		}
	case *types.Ptr:
		return fmt.Sprintf("%s((uint64_t)(uintptr_t)(%s))", g.hashMixFnName(), expr)
	case *types.Primitive:
		if v.IsInteger() || v.Kind == types.PrimBool || v.Kind == types.PrimChar {
			return fmt.Sprintf("%s((uint64_t)(%s))", g.hashMixFnName(), expr)
		}
	}
	panic(fmt.Sprintf("ICE: no C hash implementation for %s", t.String()))
}

func CanCopyType(prog *ir.Program, t types.Type) bool {
	return canCopyVisited(prog, t, make(map[types.Type]bool))
}

func (g *cEmitter) canCopy(t types.Type) bool {
	return CanCopyType(g.prog, t)
}

func canCopyVisited(prog *ir.Program, t types.Type, seen map[types.Type]bool) bool {
	if t == nil {
		return false
	}
	if t.IsPlain() {
		return true
	}
	if prog.Checked.LookupConcreteMethod(t, "copy") != nil {
		return true
	}
	switch v := t.(type) {
	case *types.Primitive:
		return v.Kind == types.PrimString
	case *types.Vector:
		return canCopyVisited(prog, v.Elem, seen)
	case *types.StackArray:
		return canCopyVisited(prog, v.Elem, seen)
	case *types.Distinct:
		return canCopyVisited(prog, v.Base, seen)
	case *types.Interface:
		return !v.UsesSelf
	case *types.Func:
		return true
	default:
		return false
	}
}

func (g *cEmitter) toStrFn(t types.Type) string {
	if custom := g.prog.Checked.LookupConcreteMethod(t, "to_string"); custom != nil {
		return custom.CName
	}
	switch t.(type) {
	case *types.Ptr, *types.Ref:
		return "ll_tostr_ptr"
	}
	if CanToStringType(g.prog, t) {
		return ir.ToStrFnName(t)
	}
	panic(fmt.Sprintf("ICE: no C to_string implementation for %s", t.String()))
}

func (g *cEmitter) canToString(t types.Type) bool {
	return CanToStringType(g.prog, t)
}

// stripOuterParens removes redundant balanced outer parentheses around a C condition
// expression so Clang `-Wparentheses-equality` never warns on `if (((a) == (b)))`.
func stripOuterParens(s string) string {
	for {
		s = strings.TrimSpace(s)
		if len(s) < 2 || s[0] != '(' || s[len(s)-1] != ')' {
			return s
		}
		depth := 0
		inStr := false
		inChar := false
		wrapsAll := true
		for i := 0; i < len(s)-1; i++ {
			ch := s[i]
			if inStr {
				if ch == '\\' {
					i++
				} else if ch == '"' {
					inStr = false
				}
				continue
			}
			if inChar {
				if ch == '\\' {
					i++
				} else if ch == '\'' {
					inChar = false
				}
				continue
			}
			switch ch {
			case '"':
				inStr = true
			case '\'':
				inChar = true
			case '(':
				depth++
			case ')':
				depth--
				if depth == 0 {
					wrapsAll = false
				}
			}
			if !wrapsAll {
				break
			}
		}
		if !wrapsAll || depth != 1 {
			return s
		}
		s = s[1 : len(s)-1]
	}
}

func (g *cEmitter) emitBakedStaticStorageAndGlobals() {
	var collected []*ir.StaticVal
	if g.unitMode != UnitPackage {
		for _, gl := range g.prog.Globals {
			if gl.IsConst && gl.StaticInit != nil {
				continue
			}
			for _, ins := range gl.InitInstr {
				g.collectCInstrConsts(ins, &collected)
			}
			g.collectCExprConsts(gl.InitExpr, &collected)
		}
	}
	for _, fn := range g.prog.Funcs {
		if g.unitMode != UnitStandalone && !fn.IsAlwaysInline && !g.defineFuncs[fn.CName] {
			continue
		}
		for _, ins := range fn.Body {
			g.collectCInstrConsts(ins, &collected)
		}
	}

	var backingDefs []string
	var constValDefs []string
	globalInits := make(map[*ir.Global]string)
	if g.unitMode != UnitPackage {
		for _, gl := range g.prog.Globals {
			if gl.IsConst && gl.StaticInit != nil {
				globalInits[gl] = g.buildCStaticInit(gl.StaticInit, &backingDefs)
			}
		}
	}
	if g.staticValSyms == nil {
		g.staticValSyms = make(map[*ir.StaticVal]string)
	}
	for _, sv := range collected {
		if sv == nil || isImmediateCStatic(sv) {
			continue
		}
		if _, ok := g.staticValSyms[sv]; ok {
			continue
		}
		initStr := g.buildCStaticInit(sv, &backingDefs)
		sym := fmt.Sprintf("__ll_ro_val_%d", g.constArrCounter)
		g.constArrCounter++
		g.staticValSyms[sv] = sym
		constValDefs = append(constValDefs, fmt.Sprintf("static %s %s = %s;", CType(sv.Type), sym, initStr))
	}

	if len(backingDefs) > 0 || len(constValDefs) > 0 {
		g.line("/* Baked Compile-Time .rodata Storage */")
		for _, def := range backingDefs {
			g.raw(def)
		}
		for _, def := range constValDefs {
			g.raw(def)
		}
		g.line("")
	}

	if len(g.prog.Globals) > 0 {
		g.line("/* Top-Level Constants */")
		for _, gl := range g.prog.Globals {
			if gl.IsConst && gl.StaticInit != nil {
				switch g.unitMode {
				case UnitPackage:
					g.line("extern %s %s;", CType(gl.Type), gl.CName)
				case UnitLinkMain:
					g.line("%s %s = %s;", CType(gl.Type), gl.CName, globalInits[gl])
				default:
					g.line("static %s %s = %s;", CType(gl.Type), gl.CName, globalInits[gl])
				}
				continue
			}
			switch g.unitMode {
			case UnitPackage:
				g.line("extern %s %s;", CType(gl.Type), gl.CName)
			case UnitLinkMain:
				g.line("%s %s;", CType(gl.Type), gl.CName)
			default:
				g.line("static %s %s;", CType(gl.Type), gl.CName)
			}
		}
		g.line("")
	}
}

func (g *cEmitter) collectCInstrConsts(ins ir.Instr, out *[]*ir.StaticVal) {
	if ins == nil {
		return
	}
	switch v := ins.(type) {
	case *ir.InstrAssign:
		g.collectCExprConsts(v.Dst, out)
		g.collectCExprConsts(v.Expr, out)
	case *ir.InstrCompoundAssign:
		g.collectCExprConsts(v.Dst, out)
		g.collectCExprConsts(v.Expr, out)
	case *ir.InstrExpr:
		g.collectCExprConsts(v.Expr, out)
	case *ir.InstrIf:
		g.collectCExprConsts(v.Cond, out)
		for _, in := range v.Then {
			g.collectCInstrConsts(in, out)
		}
		for _, in := range v.Else {
			g.collectCInstrConsts(in, out)
		}
	case *ir.InstrWhile:
		g.collectCExprConsts(v.Cond, out)
		for _, in := range v.Body {
			g.collectCInstrConsts(in, out)
		}
	case *ir.InstrBlock:
		for _, in := range v.Body {
			g.collectCInstrConsts(in, out)
		}
	case *ir.InstrReturn:
		g.collectCExprConsts(v.Expr, out)
	}
}

func (g *cEmitter) collectCExprConsts(e ir.Expr, out *[]*ir.StaticVal) {
	if e == nil {
		return
	}
	switch v := e.(type) {
	case *ir.ExprConst:
		if v.Static != nil {
			*out = append(*out, v.Static)
		}
	case *ir.ExprBinary:
		g.collectCExprConsts(v.Left, out)
		g.collectCExprConsts(v.Right, out)
	case *ir.ExprUnary:
		g.collectCExprConsts(v.Operand, out)
	case *ir.ExprCast:
		g.collectCExprConsts(v.Val, out)
	case *ir.ExprFloatBits:
		g.collectCExprConsts(v.Val, out)
	case *ir.ExprField:
		g.collectCExprConsts(v.Base, out)
	case *ir.ExprIndex:
		g.collectCExprConsts(v.Base, out)
		g.collectCExprConsts(v.Index, out)
	case *ir.ExprDeref:
		g.collectCExprConsts(v.Ptr, out)
	case *ir.ExprAddrOf:
		g.collectCExprConsts(v.Place, out)
	case *ir.ExprCall:
		g.collectCExprConsts(v.Callee, out)
		for _, a := range v.Args {
			g.collectCExprConsts(a, out)
		}
	case *ir.ExprConstructStruct:
		for _, f := range v.Fields {
			g.collectCExprConsts(f.Value, out)
		}
	case *ir.ExprConstructEnum:
		g.collectCExprConsts(v.Payload, out)
	case *ir.ExprConstructArray:
		for _, el := range v.Elems {
			g.collectCExprConsts(el, out)
		}
	case *ir.ExprConstructVector:
		for _, el := range v.Elems {
			g.collectCExprConsts(el, out)
		}
	case *ir.ExprConstructTuple:
		for _, el := range v.Elems {
			g.collectCExprConsts(el, out)
		}
	case *ir.ExprConstructClosure:
		g.collectCExprConsts(v.EnvPtr, out)
	case *ir.ExprFnToClosure:
		g.collectCExprConsts(v.Fn, out)
	case *ir.ExprWrapOptional:
		g.collectCExprConsts(v.Value, out)
	case *ir.ExprOptionalHasValue:
		g.collectCExprConsts(v.Opt, out)
	case *ir.ExprOptionalValue:
		g.collectCExprConsts(v.Opt, out)
	case *ir.ExprOptionalValuePtr:
		g.collectCExprConsts(v.OptPtr, out)
	case *ir.ExprSliceView:
		g.collectCExprConsts(v.DataPtr, out)
		g.collectCExprConsts(v.Len, out)
	case *ir.ExprBoxInterface:
		g.collectCExprConsts(v.Value, out)
	case *ir.ExprAlloc:
		g.collectCExprConsts(v.Count, out)
	case *ir.ExprFree:
		g.collectCExprConsts(v.Ptr, out)
	case *ir.ExprRealloc:
		g.collectCExprConsts(v.Ptr, out)
		g.collectCExprConsts(v.Count, out)
	case *ir.ExprCopyBytes:
		g.collectCExprConsts(v.Dst, out)
		g.collectCExprConsts(v.Src, out)
		g.collectCExprConsts(v.Count, out)
	case *ir.ExprToString:
		g.collectCExprConsts(v.Val, out)
	case *ir.ExprDrop:
		g.collectCExprConsts(v.Ptr, out)
	case *ir.ExprCopy:
		g.collectCExprConsts(v.Val, out)
	case *ir.ExprEq:
		g.collectCExprConsts(v.Left, out)
		g.collectCExprConsts(v.Right, out)
	case *ir.ExprCmp:
		g.collectCExprConsts(v.Left, out)
		g.collectCExprConsts(v.Right, out)
	case *ir.ExprHash:
		g.collectCExprConsts(v.Val, out)
	case *ir.ExprVecPush:
		g.collectCExprConsts(v.VecPtr, out)
		g.collectCExprConsts(v.Item, out)
	}
}

func isImmediateCStatic(sv *ir.StaticVal) bool {
	if sv == nil {
		return true
	}
	switch sv.Kind {
	case sema.StaticVoid, sema.StaticInt, sema.StaticFloat, sema.StaticBool, sema.StaticChar:
		return true
	case sema.StaticFn:
		if fnTy, ok := unwrapDistinctType(sv.Type).(*types.Func); ok && fnTy.Closure {
			return false
		}
		return true
	case sema.StaticEnum:
		effTy := unwrapDistinctType(sv.Type)
		if en, ok := effTy.(*types.Enum); ok && !en.IsTagged {
			return true
		}
	case sema.StaticOpt:
		effTy := unwrapDistinctType(sv.Type)
		if opt, ok := effTy.(*types.Optional); ok && opt.IsBoxed() {
			return !sv.HasOpt
		}
	}
	return false
}

func formatCStaticScalar(sv *ir.StaticVal, fallbackTy types.Type) string {
	ty := sv.Type
	if ty == nil {
		ty = fallbackTy
	}
	switch sv.Kind {
	case sema.StaticVoid:
		return ""
	case sema.StaticInt:
		if sv.IsSigned && sv.SignedVal < 0 {
			return formatCIntLit(uint64(-sv.SignedVal), true, ty)
		}
		return formatCIntLit(sv.Uint, false, ty)
	case sema.StaticFloat:
		return formatCFloatLit(sv.Float, ty)
	case sema.StaticBool:
		if sv.Bool {
			return "true"
		}
		return "false"
	case sema.StaticChar:
		return fmt.Sprintf("%du", uint32(sv.Char))
	case sema.StaticFn:
		if sv.FnEntry == "" {
			return fmt.Sprintf("((%s)NULL)", CType(ty))
		}
		return fmt.Sprintf("((%s)%s)", CType(ty), sv.FnEntry)
	case sema.StaticEnum:
		return fmt.Sprintf("((%s)%dLL)", CType(ty), sv.VariantVal)
	case sema.StaticOpt:
		if sv.HasOpt {
			panic(fmt.Sprintf("ICE: cannot emit non-none boxed StaticOpt %s as immediate C static", ty.String()))
		}
		return fmt.Sprintf("((%s)NULL)", CType(ty))
	}
	return "0"
}

func (g *cEmitter) buildCStaticInit(sv *ir.StaticVal, backingDefs *[]string) string {
	if sv == nil {
		return "{ 0 }"
	}
	if isImmediateCStatic(sv) {
		return formatCStaticScalar(sv, sv.Type)
	}
	effTy := unwrapDistinctType(sv.Type)
	switch sv.Kind {
	case sema.StaticString:
		if len(sv.Str) == 0 {
			return "{ .data = (uint8_t*)\"\", .len = 0LL, .cap = 0LL }"
		}
		return fmt.Sprintf("{ .data = (uint8_t*)%s, .len = %dLL, .cap = 0LL }", quoteCString(sv.Str), len(sv.Str))
	case sema.StaticList:
		if sv.HasRawBytes {
			if len(sv.RawBytes) == 0 {
				return "{ .data = NULL, .len = 0LL, .cap = 0LL }"
			}
			arrSym := fmt.Sprintf("__ll_ro_arr_%d", g.constArrCounter)
			g.constArrCounter++
			var sb strings.Builder
			for i, b := range sv.RawBytes {
				if i > 0 {
					sb.WriteString(", ")
				}
				fmt.Fprintf(&sb, "%d", b)
			}
			*backingDefs = append(*backingDefs, fmt.Sprintf("static const uint8_t %s[%d] = { %s };",
				arrSym, len(sv.RawBytes), sb.String()))
			return fmt.Sprintf("{ .data = (uint8_t*)%s, .len = %dLL, .cap = 0LL }", arrSym, len(sv.RawBytes))
		}
		if len(sv.Elems) == 0 {
			return "{ .data = NULL, .len = 0LL, .cap = 0LL }"
		}
		var elemTy types.Type
		if vec, ok := effTy.(*types.Vector); ok {
			elemTy = vec.Elem
		} else if st, ok := effTy.(*types.Struct); ok && len(st.TypeArgs) == 1 {
			elemTy = st.TypeArgs[0]
		}
		cElem := CType(elemTy)
		parts := make([]string, len(sv.Elems))
		for i, el := range sv.Elems {
			parts[i] = g.buildCStaticInit(el, backingDefs)
		}
		arrSym := fmt.Sprintf("__ll_ro_arr_%d", g.constArrCounter)
		g.constArrCounter++
		*backingDefs = append(*backingDefs, fmt.Sprintf("static const %s %s[%d] = { %s };",
			cElem, arrSym, len(sv.Elems), strings.Join(parts, ", ")))
		return fmt.Sprintf("{ .data = (%s*)%s, .len = %dLL, .cap = 0LL }", cElem, arrSym, len(sv.Elems))
	case sema.StaticArray:
		if len(sv.Elems) == 0 {
			return "{ 0 }"
		}
		parts := make([]string, len(sv.Elems))
		for i, el := range sv.Elems {
			parts[i] = g.buildCStaticInit(el, backingDefs)
		}
		return fmt.Sprintf("{ .data = { %s } }", strings.Join(parts, ", "))
	case sema.StaticTuple:
		if len(sv.Elems) == 0 {
			return "{ 0 }"
		}
		parts := make([]string, len(sv.Elems))
		for i, el := range sv.Elems {
			parts[i] = fmt.Sprintf("._%d = %s", i, g.buildCStaticInit(el, backingDefs))
		}
		return fmt.Sprintf("{ %s }", strings.Join(parts, ", "))
	case sema.StaticStruct:
		if len(sv.Fields) == 0 {
			return "{ 0 }"
		}
		parts := make([]string, len(sv.Fields))
		for i, f := range sv.Fields {
			parts[i] = fmt.Sprintf(".%s = %s", f.Name, g.buildCStaticInit(f.Value, backingDefs))
		}
		return fmt.Sprintf("{ %s }", strings.Join(parts, ", "))
	case sema.StaticEnum:
		if sv.Payload != nil {
			return fmt.Sprintf("{ .tag = %d, .data = { .%s = %s } }",
				sv.VariantVal, sv.VariantCN, g.buildCStaticInit(sv.Payload, backingDefs))
		}
		return fmt.Sprintf("{ .tag = %d }", sv.VariantVal)
	case sema.StaticFn:
		if fnTy, ok := unwrapDistinctType(sv.Type).(*types.Func); ok && fnTy.Closure {
			fnExpr := "NULL"
			if sv.FnEntry != "" {
				fnExpr = sv.FnEntry
			}
			return fmt.Sprintf("{ .fn = %s, .env = NULL, .copy_env = NULL, .drop_env = NULL }", fnExpr)
		}
		return formatCStaticScalar(sv, sv.Type)
	case sema.StaticOpt:
		if opt, ok := unwrapDistinctType(sv.Type).(*types.Optional); ok && opt.IsBoxed() {
			if sv.HasOpt {
				panic(fmt.Sprintf("ICE: cannot emit non-none boxed StaticOpt %s in C static init", sv.Type.String()))
			}
			return fmt.Sprintf("((%s)NULL)", CType(sv.Type))
		}
		if !sv.HasOpt {
			return "{ .has_value = false }"
		}
		return fmt.Sprintf("{ .has_value = true, .value = %s }", g.buildCStaticInit(sv.OptElem, backingDefs))
	}
	return "{ 0 }"
}

func (g *cEmitter) emitCExprConst(sv *ir.StaticVal, fallbackTy types.Type) string {
	if sv == nil {
		return "0"
	}
	if isImmediateCStatic(sv) {
		return formatCStaticScalar(sv, fallbackTy)
	}
	if sym, ok := g.staticValSyms[sv]; ok {
		return sym
	}
	ty := sv.Type
	if ty == nil {
		ty = fallbackTy
	}
	return fmt.Sprintf("((%s){ 0 })", CType(ty))
}
