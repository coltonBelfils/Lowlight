// EmitC generates a complete, standalone ISO C11 translation unit from `prog`.
func EmitC(prog *ir.Program) string {
	g := &cEmitter{
		prog:   prog,
		optSet: make(map[string]bool),
		vecSet: make(map[string]bool),
	}
	for _, o := range prog.Optionals {
		g.optSet[o.Mangled()] = true
	}
	for _, st := range prog.Structs {
		if st.BoxedOptional {
			g.optSet[types.NewOptional(st).Mangled()] = true
		}
	}
	for _, v := range prog.Vectors {
		g.vecSet[v.Mangled()] = true
	}

	g.emitAll()
	return g.sb.String()
}

type cEmitter struct {
	prog        *ir.Program
	unitMode    UnitMode
	defineFuncs map[string]bool
	sb          strings.Builder
	optSet      map[string]bool
	vecSet      map[string]bool
	// externAliases maps a user `extern` function's C symbol to the primary private name, while
	// externAliasesByEF and externAliasSigs distinguish duplicate C symbols with differing signatures.
	externAliases     map[string]string
	externAliasesByEF map[*sema.ExternFunc]string
	externAliasSigs   map[string]string
	staticValSyms     map[*ir.StaticVal]string
	constArrCounter int
	loweredLambdas  map[*sema.LambdaInfo]bool
}

func (g *cEmitter) isLambdaLowered(li *sema.LambdaInfo) bool {
	if li == nil {
		return false
	}
	if g.loweredLambdas == nil {
		g.loweredLambdas = make(map[*sema.LambdaInfo]bool)
		if g.prog != nil {
			for _, fn := range g.prog.Funcs {
				if fn.IsLambda && fn.LambdaInfo != nil {
					g.loweredLambdas[fn.LambdaInfo] = true
				}
			}
		}
	}
	return g.loweredLambdas[li]
}

func (g *cEmitter) raw(s string) {
	g.sb.WriteString(s)
	g.sb.WriteByte('\n')
}

func (g *cEmitter) line(format string, args ...any) {
	if len(args) == 0 {
		g.sb.WriteString(format)
		g.sb.WriteByte('\n')
		return
	}
	g.sb.WriteString(fmt.Sprintf(format, args...))
	g.sb.WriteByte('\n')
}

func (g *cEmitter) indentLine(indent int, format string, args ...any) {
	for i := 0; i < indent; i++ {
		g.sb.WriteString("    ")
	}
	g.line(format, args...)
}

func (g *cEmitter) hasOptionalType(o *types.Optional) bool {
	return g.optSet[o.Mangled()]
}

func (g *cEmitter) hasVectorType(v *types.Vector) bool {
	return g.vecSet[v.Mangled()]
}

func (g *cEmitter) emitAll() {
	// 1. Embedded C11 Runtime Header + User `extern "<header>"` includes
	g.line("/* Generated by the Lowlight compiler. Compile with -fno-strict-aliasing: `ptr_cast`")
	g.line("   lets Lowlight code view memory as another type. */")
	if g.unitMode == UnitPackage {
		g.line("#define LL_UNIT_PKG 1")
	} else if g.unitMode == UnitLinkMain {
		g.line("#define LL_RT_GLOBAL")
	}
	g.sb.WriteString(RuntimeHeaderC11)
	if len(g.prog.ExternHeaders) > 0 {
		g.line("/* User Extern Headers */")
		for _, hdr := range g.prog.ExternHeaders {
			if strings.HasPrefix(hdr, "./") || strings.HasPrefix(hdr, "../") || strings.HasPrefix(hdr, "/") {
				g.line("#include %q", hdr)
			} else {
				g.line("#include <%s>", hdr)
			}
		}
		g.line("")
	}

	// 2. Enum Typedefs & Forward Struct Declarations
	g.emitEnumsAndForwardDecls()

	// 3. Topologically Ordered Concrete Type Definitions
	g.emitOrderedTypeDefs()

	// 4. Lambda Environment Structs
	g.emitLambdaEnvStructs()

	// 5. Forward Function & Helper Prototypes (breaks all mutual cycles cleanly)
	g.emitForwardPrototypes()

	// 6. Synthesized Type Lifecycle Helpers (`drop`, `copy`, `eq`, `hash`, `to_string`, collections)
	g.emitSynthesizedTypeHelpers()

	// 7. Lambda Env Helpers, Static Closure Thunks, & Interface VTables
	g.emitLambdaAndThunkHelpers()
	g.emitVTables()

	// 8. Baked Compile-Time `.rodata` Arrays & Top-Level `bind`/`const` Globals
	g.emitBakedStaticStorageAndGlobals()

	// 9. Lowered MIR Function & Lambda Bodies
	g.line("/* Lowered Lowlight Functions */")
	for _, fn := range g.prog.Funcs {
		if g.unitMode != UnitStandalone && !fn.IsAlwaysInline && !g.defineFuncs[fn.CName] {
			continue
		}
		g.emitFunction(fn)
	}

	// 10. C11 `main` Entry Point (if `MainFunc` is present or in `TestMode`)
	if g.unitMode != UnitPackage && (g.prog.MainFunc != nil || g.prog.TestMode) {
		g.emitCMain()
	}
}

