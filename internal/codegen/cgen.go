// Section 2 & 3: Enums, Forward Declarations, & Ordered Struct Definitions
// -----------------------------------------------------------------------------

func (g *cEmitter) emitEnumsAndForwardDecls() {
	if len(g.prog.Enums) > 0 {
		g.line("/* Enum Types */")
		for _, en := range g.prog.Enums {
			g.line("typedef %s %s;", CType(en.Underlying), en.CName)
			for _, v := range en.Variants {
				g.line("#define %s__%s ((%s)%dLL)", en.CName, v.Name, en.CName, v.Value)
			}
		}
		g.line("")
	}

	g.line("/* Forward Struct Declarations */")
	for _, t := range g.prog.OrderedTypes {
		switch v := t.(type) {
		case *types.Enum:
			g.line("typedef struct %s %s;", v.CName, v.CName)
		case *types.Struct:
			if strings.HasPrefix(v.CName, "ll_lambda_env_") {
				continue
			}
			if (v.Name == "List" || strings.HasPrefix(v.Name, "List[")) && len(v.TypeArgs) == 1 {
				g.line("typedef struct ll_vec_%s %s;", v.TypeArgs[0].Mangled(), v.CName)
				continue
			}
			g.line("typedef struct %s %s;", v.CName, v.CName)
		case *types.Optional:
			if !v.IsBoxed() {
				cn := CType(v)
				g.line("typedef struct %s %s;", cn, cn)
			}
		case *types.StackArray:
			cn := CType(v)
			g.line("typedef struct %s %s;", cn, cn)
		case *types.Tuple:
			cn := CType(v)
			g.line("typedef struct %s %s;", cn, cn)
		case *types.Vector:
			cn := CType(v)
			g.line("typedef struct %s %s;", cn, cn)
		case *types.Func:
			if v.Closure {
				cn := CType(v)
				g.line("typedef struct %s %s;", cn, cn)
			}
		case *types.Interface:
			vt := ir.VTableTypeName(v)
			g.line("typedef struct %s %s;", vt, vt)
			g.line("typedef struct %s %s;", v.CName, v.CName)
		}
	}
	for _, t := range g.prog.OrderedTypes {
		if v, ok := t.(*types.Distinct); ok {
			g.line("typedef %s %s;", CType(v.Base), v.CName)
		}
	}
	// An `fn` value is a pointer to an entry function taking the (unused) environment first,
	// like a closure's `fn` field.
	for _, t := range g.prog.OrderedTypes {
		if v, ok := t.(*types.Func); ok && !v.Closure {
			pTypes := []string{"void*"}
			if v.Extern {
				pTypes = nil // a C function pointer takes just its arguments
			}
			for _, p := range v.Params {
				pTypes = append(pTypes, paramCType(p.Mode, p.Type))
			}
			if len(pTypes) == 0 {
				pTypes = []string{"void"}
			}
			g.line("typedef %s (*%s)(%s);", CType(v.Ret), CType(v), strings.Join(pTypes, ", "))
		}
	}
	g.line("")
}

func (g *cEmitter) emitOrderedTypeDefs() {
	g.line("/* Concrete & Monomorphized Type Definitions */")
	for _, t := range g.prog.OrderedTypes {
		switch v := t.(type) {
		case *types.Enum:
			hasPayload := false
			for _, vr := range v.Variants {
				if vr.Kind != types.VariantUnit {
					hasPayload = true
					break
				}
			}
			g.line("struct %s {", v.CName)
			g.line("    int32_t tag;")
			if hasPayload {
				g.line("    union {")
				for _, vr := range v.Variants {
					if vr.Kind == types.VariantTuple {
						g.line("        %s %s;", CType(vr.Payload), vr.CName)
					}
				}
				g.line("    } data;")
			}
			g.line("};")

		case *types.Struct:
			if strings.HasPrefix(v.CName, "ll_lambda_env_") {
				continue
			}
			if (v.Name == "List" || strings.HasPrefix(v.Name, "List[")) && len(v.TypeArgs) == 1 {
				continue
			}
			attr := ""
			if v.Packed {
				attr = " __attribute__((packed))"
			}
			g.line("struct%s %s {", attr, v.CName)
			if len(v.Fields) == 0 {
				g.line("    uint8_t _ll_empty;")
			} else {
				for _, f := range v.Fields {
					g.line("    %s %s;", CType(f.Type), f.CName)
				}
			}
			g.line("};")

		case *types.Optional:
			if !v.IsBoxed() {
				cn := CType(v)
				g.line("struct %s { bool has_value; %s value; };", cn, CType(v.Elem))
			}

		case *types.StackArray:
			cn := CType(v)
			g.line("struct %s { %s data[%d]; };", cn, CType(v.Elem), v.Size)

		case *types.Tuple:
			cn := CType(v)
			g.line("struct %s {", cn)
			if len(v.Elems) == 0 {
				g.line("    uint8_t _ll_empty;")
			} else {
				for i, el := range v.Elems {
					g.line("    %s _%d;", CType(el), i)
				}
			}
			g.line("};")

		case *types.Vector:
			cn := CType(v)
			g.line("struct %s { %s* data; int64_t len; int64_t cap; };", cn, CType(v.Elem))

		case *types.Func:
			if !v.Closure {
				continue
			}
			cn := CType(v)
			pTypes := []string{"void*"}
			for _, p := range v.Params {
				pTypes = append(pTypes, paramCType(p.Mode, p.Type))
			}
			g.line("struct %s {", cn)
			g.line("    %s (*fn)(%s);", CType(v.Ret), strings.Join(pTypes, ", "))
			g.line("    void* env;")
			g.line("    void* (*copy_env)(const void*);")
			g.line("    void (*drop_env)(void*);")
			g.line("};")

		case *types.Interface:
			vt := ir.VTableTypeName(v)
			g.line("struct %s {", vt)
			g.line("    void (*drop_box)(void*);")
			g.line("    void* (*clone_box)(const void*);")
			for _, m := range v.Methods {
				pTypes := []string{"void*"}
				for _, p := range m.Params {
					pTypes = append(pTypes, paramCType(p.Mode, p.Type))
				}
				g.line("    %s (*m_%s)(%s);", CType(m.Ret), m.Name, strings.Join(pTypes, ", "))
			}
			g.line("};")
			g.line("struct %s { void* data; const %s* vtable; bool owned; };", v.CName, vt)
		}
	}
	g.line("")
}

func (g *cEmitter) emitLambdaEnvStructs() {
	if len(g.prog.Checked.Lambdas) == 0 {
		return
	}
	g.line("/* Closure Capture Environments */")
	for _, li := range g.prog.Checked.Lambdas {
		if len(li.Captures) == 0 || !g.isLambdaLowered(li) {
			continue
		}
		g.line("typedef struct %s {", li.EnvCName)
		for _, c := range li.Captures {
			g.line("    %s %s;", CType(c.Type), c.CName)
		}
		g.line("} %s;", li.EnvCName)
	}
	g.line("")
}

