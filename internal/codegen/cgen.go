func (g *cEmitter) canCmp(t types.Type) bool {
	if custom := g.prog.Checked.LookupConcreteMethod(t, "cmp"); custom != nil {
		return true
	}
	if p, isPrim := t.(*types.Primitive); isPrim {
		return p.IsNumeric() || p.Kind == types.PrimBool || p.Kind == types.PrimChar || p.Kind == types.PrimString
	}
	switch v := t.(type) {
	case *types.Distinct:
		return g.canCmp(v.Base)
	case *types.Enum:
		return !v.IsTagged
	case *types.Tuple:
		if len(v.Elems) == 0 {
			return false
		}
		for _, el := range v.Elems {
			if !g.canCmp(el) {
				return false
			}
		}
		return true
	}
	return false
}

func (g *cEmitter) cmpInlineExpr(t types.Type, a, b string) string {
	if customCmp := g.prog.Checked.LookupConcreteMethod(t, "cmp"); customCmp != nil {
		return fmt.Sprintf("%s(%s, %s)", customCmp.CName, a, b)
	}
	if p, isPrim := t.(*types.Primitive); isPrim {
		if p.Kind == types.PrimString {
			if cmpM := g.prog.Checked.LookupConcreteMethod(types.TypeString, "cmp"); cmpM != nil {
				return fmt.Sprintf("%s(%s, %s)", cmpM.CName, a, b)
			}
		}
		return fmt.Sprintf("(((%s) < (%s)) ? -1LL : (((%s) > (%s)) ? 1LL : 0LL))", a, b, a, b)
	}
	switch v := t.(type) {
	case *types.Distinct:
		return g.cmpInlineExpr(v.Base, fmt.Sprintf("(%s)(%s)", CType(v.Base), a), fmt.Sprintf("(%s)(%s)", CType(v.Base), b))
	case *types.Tuple:
		return fmt.Sprintf("%s(%s, %s)", ir.CmpFnName(v), a, b)
	case *types.Enum:
		if !v.IsTagged {
			return fmt.Sprintf("(((%s) < (%s)) ? -1LL : (((%s) > (%s)) ? 1LL : 0LL))", a, b, a, b)
		}
	}
	return "0LL"
}

func (g *cEmitter) copyExpr(t types.Type) string {
	if custom := g.prog.Checked.LookupConcreteMethod(t, "copy"); custom != nil {
		return custom.CName
	}
	if t.IsPlain() {
		return ""
	}
	return ir.CopyFnName(t)
}

func (g *cEmitter) eqInlineExpr(t types.Type, a, b string) string {
	if p, isPrim := t.(*types.Primitive); isPrim && p.Kind != types.PrimString {
		return fmt.Sprintf("((%s) == (%s))", a, b)
	}
	if custom := g.prog.Checked.LookupConcreteMethod(t, "eq"); custom != nil {
		return fmt.Sprintf("%s(%s, %s)", custom.CName, a, b)
	}
	if customCmp := g.prog.Checked.LookupConcreteMethod(t, "cmp"); customCmp != nil {
		return fmt.Sprintf("(%s(%s, %s) == 0)", customCmp.CName, a, b)
	}
	switch v := t.(type) {
	case *types.Primitive:
		if v.Kind == types.PrimString {
			if eqM := g.prog.Checked.LookupConcreteMethod(types.TypeString, "eq"); eqM != nil {
				return fmt.Sprintf("%s(%s, %s)", eqM.CName, a, b)
			}
		}
		return fmt.Sprintf("((%s) == (%s))", a, b)
	case *types.Enum:
		if v.IsTagged {
			return fmt.Sprintf("%s(%s, %s)", ir.EqFnName(t), a, b)
		}
		return fmt.Sprintf("((%s) == (%s))", a, b)
	case *types.Ptr, *types.Ref:
		return fmt.Sprintf("((%s) == (%s))", a, b)
	case *types.Distinct:
		cBase := CType(v.Base)
		return g.eqInlineExpr(v.Base, fmt.Sprintf("((%s)(%s))", cBase, a), fmt.Sprintf("((%s)(%s))", cBase, b))
	case *types.Struct, *types.Optional, *types.Tuple:
		return fmt.Sprintf("%s(%s, %s)", ir.EqFnName(t), a, b)
	default:
		return fmt.Sprintf("((%s) == (%s))", a, b)
	}
}

func (g *cEmitter) hashInlineExpr(t types.Type, expr string) string {
	if custom := g.prog.Checked.LookupConcreteMethod(t, "hash"); custom != nil {
		return fmt.Sprintf("%s(%s)", custom.CName, expr)
	}
	switch v := t.(type) {
	case *types.Distinct:
		return fmt.Sprintf("%s(%s)", ir.HashFnName(v), expr)
	case *types.Tuple:
		return fmt.Sprintf("%s(%s)", ir.HashFnName(v), expr)
	case *types.Enum:
		return fmt.Sprintf("%s((uint64_t)(%s))", g.hashMixFnName(), expr)
	case *types.Ptr:
		return fmt.Sprintf("%s((uint64_t)(uintptr_t)(%s))", g.hashMixFnName(), expr)
	default:
		return fmt.Sprintf("%s((uint64_t)(%s))", g.hashMixFnName(), expr)
	}
}

func CanCopyType(prog *ir.Program, t types.Type) bool {
	return canCopyVisited(prog, t, make(map[types.Type]bool))
}

func (g *cEmitter) canCopy(t types.Type) bool {
	return CanCopyType(g.prog, t)
}

func canCopyVisited(prog *ir.Program, t types.Type, seen map[types.Type]bool) bool {
	if t == nil {
		return false
	}
	if t.IsPlain() {
		return true
	}
	if prog.Checked.LookupConcreteMethod(t, "copy") != nil {
		return true
	}
	switch v := t.(type) {
	case *types.Primitive:
		return v.Kind == types.PrimString
	case *types.Vector:
		return canCopyVisited(prog, v.Elem, seen)
	case *types.StackArray:
		return canCopyVisited(prog, v.Elem, seen)
	case *types.Tuple:
		for _, el := range v.Elems {
			if !canCopyVisited(prog, el, seen) {
				return false
			}
		}
		return true
	case *types.Optional:
		return canCopyVisited(prog, v.Elem, seen)
	case *types.Distinct:
		return canCopyVisited(prog, v.Base, seen)
	case *types.Interface:
		return !v.UsesSelf
	case *types.Func:
		return true
	case *types.Enum:
		if v.HasCustomDrop {
			return false
		}
		if !v.IsTagged || seen[v] {
			return true
		}
		seen[v] = true
		for _, vr := range v.Variants {
			if vr.Kind == types.VariantTuple && vr.Payload != nil && !canCopyVisited(prog, vr.Payload, seen) {
				return false
			}
		}
		return true
	case *types.Struct:
		if v.HasCustomDrop {
			return false
		}
		if seen[v] {
			return true
		}
		seen[v] = true
		for _, f := range v.Fields {
			if !canCopyVisited(prog, f.Type, seen) {
				return false
			}
		}
		return true
	default:
		return false
	}
}

func (g *cEmitter) toStrFn(t types.Type) string {
	if custom := g.prog.Checked.LookupConcreteMethod(t, "to_string"); custom != nil {
		return custom.CName
	}
	switch t.(type) {
	case *types.Ptr, *types.Ref:
		return "ll_tostr_ptr"
	}
	return ir.ToStrFnName(t)
}

func (g *cEmitter) canToString(t types.Type) bool {
	return g.canToStringVisited(t, make(map[types.Type]bool))
}

func (g *cEmitter) canToStringVisited(t types.Type, seen map[types.Type]bool) bool {
	if t == nil {
		return false
	}
	if g.prog.Checked.LookupConcreteMethod(t, "to_string") != nil {
		return true
	}
	switch v := t.(type) {
	case *types.Primitive:
		return v.Kind != types.PrimVoid && v.Kind != types.PrimArena
	case *types.Ptr, *types.Ref:
		return true
	case *types.Enum:
		if !v.IsTagged || seen[v] {
			return true
		}
		seen[v] = true
		for _, vr := range v.Variants {
			if vr.Kind == types.VariantTuple && vr.Payload != nil && !g.canToStringVisited(vr.Payload, seen) {
				return false
			}
		}
		return true
	case *types.Distinct:
		return g.canToStringVisited(v.Base, seen)
	case *types.Vector:
		return g.canToStringVisited(v.Elem, seen)
	case *types.StackArray:
		return g.canToStringVisited(v.Elem, seen)
	case *types.Tuple:
		for _, el := range v.Elems {
			if !g.canToStringVisited(el, seen) {
				return false
			}
		}
		return true
	case *types.Optional:
		return g.canToStringVisited(v.Elem, seen)
	case *types.Interface:
		return v == g.prog.Checked.IfacePrintable
	default:
		return false
	}
}

// stripOuterParens removes redundant balanced outer parentheses around a C condition
// expression so Clang `-Wparentheses-equality` never warns on `if (((a) == (b)))`.
func stripOuterParens(s string) string {
	for {
		s = strings.TrimSpace(s)
		if len(s) < 2 || s[0] != '(' || s[len(s)-1] != ')' {
			return s
		}
		depth := 0
		inStr := false
		inChar := false
		wrapsAll := true
		for i := 0; i < len(s)-1; i++ {
			ch := s[i]
			if inStr {
				if ch == '\\' {
					i++
				} else if ch == '"' {
					inStr = false
				}
				continue
			}
			if inChar {
				if ch == '\\' {
					i++
				} else if ch == '\'' {
					inChar = false
				}
				continue
			}
			switch ch {
			case '"':
				inStr = true
			case '\'':
				inChar = true
			case '(':
				depth++
			case ')':
				depth--
				if depth == 0 {
					wrapsAll = false
				}
			}
			if !wrapsAll {
				break
			}
		}
		if !wrapsAll || depth != 1 {
			return s
		}
		s = s[1 : len(s)-1]
	}
}
