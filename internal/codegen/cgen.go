func (g *cEmitter) emitLambdaAndThunkHelpers() {
	for _, li := range g.prog.Checked.Lambdas {
		if !g.isLambdaLowered(li) {
			continue
		}
		if len(li.Captures) > 0 {
			// env drop
			g.line("static inline void %s_drop(void* _raw) {", li.EnvCName)
			g.line("    if (!_raw) return;")
			g.line("    %s* e = (%s*)_raw;", li.EnvCName, li.EnvCName)
			g.line("    (void)e;")
			for i := len(li.Captures) - 1; i >= 0; i-- {
				c := li.Captures[i]
				if !c.Type.IsPlain() {
					g.line("    %s(&e->%s);", ir.DropFnName(c.Type), c.CName)
				}
			}
			g.line("    ll_free(e);")
			g.line("}")

			// env copy
			allCopyable := true
			for _, c := range li.Captures {
				if !g.canCopy(c.Type) {
					allCopyable = false
					break
				}
			}
			g.line("static inline void* %s_copy(const void* _raw) {", li.EnvCName)
			if !allCopyable {
				g.line("    (void)_raw; ll_panic_cstr(\"closure environment is non-copyable\", \"<lambda>\", 0);")
			} else {
				g.line("    const %s* src = (const %s*)_raw;", li.EnvCName, li.EnvCName)
				g.line("    %s* dst = (%s*)ll_alloc((int64_t)sizeof(%s));", li.EnvCName, li.EnvCName, li.EnvCName)
				for _, c := range li.Captures {
					if c.Type.IsPlain() {
						g.line("    dst->%s = src->%s;", c.CName, c.CName)
					} else {
						g.line("    dst->%s = %s(src->%s);", c.CName, g.copyExpr(c.Type), c.CName)
					}
				}
				g.line("    return (void*)dst;")
			}
			g.line("}")
		}

		// `_entry` wrapper matching `fn(void* _env, ...)` pointer signature. An `extern fn`
		// literal is called directly by C and has none.
		if li.Sig.Extern {
			continue
		}
		var pDecls []string
		var pArgs []string
		pDecls = append(pDecls, "void* _ll_env")
		pArgs = append(pArgs, "_ll_env")
		for idx, p := range li.Sig.Params {
			pn := fmt.Sprintf("_p%d", idx)
			pDecls = append(pDecls, fmt.Sprintf("%s %s", paramCType(p.Mode, p.Type), pn))
			pArgs = append(pArgs, pn)
		}
		g.line("static inline %s %s_entry(%s) {", CType(li.Sig.Ret), li.CName, strings.Join(pDecls, ", "))
		if li.Sig.Ret.Equals(types.TypeVoid) {
			g.line("    %s(%s);", li.CName, strings.Join(pArgs, ", "))
		} else {
			g.line("    return %s(%s);", li.CName, strings.Join(pArgs, ", "))
		}
		g.line("}")
	}

	// Static function closure thunks
	for _, st := range g.prog.StaticThunks {
		if st.CCallback {
			g.emitCCallbackThunk(st)
			continue
		}
		var pDecls []string
		var pArgs []string
		pDecls = append(pDecls, "void* _ll_env")
		for idx, p := range st.FuncType.Params {
			pn := fmt.Sprintf("_p%d", idx)
			pDecls = append(pDecls, fmt.Sprintf("%s %s", paramCType(p.Mode, p.Type), pn))
			pArgs = append(pArgs, pn)
		}
		targetSym := st.TargetCName()
		if alias, ok := g.externAliasBySig(targetSym, st.FuncType); ok {
			targetSym = alias
		}
		g.line("static inline %s %s(%s) {", CType(st.FuncType.Ret), st.ThunkCName, strings.Join(pDecls, ", "))
		g.line("    (void)_ll_env;")
		if st.FuncType.Ret.Equals(types.TypeVoid) {
			g.line("    %s(%s);", targetSym, strings.Join(pArgs, ", "))
		} else {
			g.line("    return %s(%s);", targetSym, strings.Join(pArgs, ", "))
		}
		g.line("}")
	}
	g.line("")
}

// emitCCallbackThunk emits a test-build wrapper for an `extern fn` that C calls: while it runs, the
// test runner's jump target is cleared, so a panic ends the test run (as in a normal build) instead
// of jumping back across the C frames.
func (g *cEmitter) emitCCallbackThunk(st *ir.StaticThunk) {
	var pDecls, pArgs []string
	for idx, p := range st.FuncType.Params {
		pn := fmt.Sprintf("_p%d", idx)
		pDecls = append(pDecls, fmt.Sprintf("%s %s", paramCType(p.Mode, p.Type), pn))
		pArgs = append(pArgs, pn)
	}
	if len(pDecls) == 0 {
		pDecls = []string{"void"}
	}
	targetSym := st.TargetCName()
	if alias, ok := g.externAliasBySig(targetSym, st.FuncType); ok {
		targetSym = alias
	}
	g.line("static %s %s(%s) {", CType(st.FuncType.Ret), st.ThunkCName, strings.Join(pDecls, ", "))
	g.line("    jmp_buf* _ll_saved = ll_test_current_jmp;")
	g.line("    ll_test_current_jmp = NULL;")
	if st.FuncType.Ret.Equals(types.TypeVoid) {
		g.line("    %s(%s);", targetSym, strings.Join(pArgs, ", "))
		g.line("    ll_test_current_jmp = _ll_saved;")
	} else {
		g.line("    %s _ll_r = %s(%s);", CType(st.FuncType.Ret), targetSym, strings.Join(pArgs, ", "))
		g.line("    ll_test_current_jmp = _ll_saved;")
		g.line("    return _ll_r;")
	}
	g.line("}")
}

func (g *cEmitter) emitVTables() {
	if len(g.prog.VTables) == 0 {
		return
	}
	g.line("/* Interface VTables */")
	for _, vt := range g.prog.VTables {
		cCon := CType(vt.Concrete)
		vtInst := ir.VTableInstanceName(vt.Concrete, vt.Iface)
		vtTy := ir.VTableTypeName(vt.Iface)
		if g.unitMode == UnitPackage {
			g.line("extern const %s %s;", vtTy, vtInst)
			continue
		}

		// drop_box
		dropName := vtInst + "__drop"
		g.line("static inline void %s(void* _data) {", dropName)
		g.line("    if (!_data) return;")
		if !vt.Concrete.IsPlain() {
			g.line("    %s((%s*)_data);", ir.DropFnName(vt.Concrete), cCon)
		}
		g.line("    ll_free(_data);")
		g.line("}")

		// clone_box
		cloneName := vtInst + "__clone"
		g.line("static inline void* %s(const void* _data) {", cloneName)
		if g.canCopy(vt.Concrete) {
			g.line("    %s* nb = (%s*)ll_alloc((int64_t)sizeof(%s));", cCon, cCon, cCon)
			g.line("    *nb = %s(*(const %s*)_data);", g.copyExpr(vt.Concrete), cCon)
			g.line("    return (void*)nb;")
		} else {
			g.line("    (void)_data; ll_panic_cstr(\"boxed interface concrete value does not support .copy()\", \"<vtable>\", 0);")
		}
		g.line("}")

		// method wrappers
		var mPtrNames []string
		for idx, im := range vt.Iface.Methods {
			wName := fmt.Sprintf("%s__m_%s", vtInst, im.Name)
			mPtrNames = append(mPtrNames, fmt.Sprintf(".m_%s = %s", im.Name, wName))

			var pDecls []string
			var callArgs []string
			pDecls = append(pDecls, "void* _self")
			if im.RecvMode == types.ModeMut {
				callArgs = append(callArgs, fmt.Sprintf("((%s*)_self)", cCon))
			} else {
				callArgs = append(callArgs, fmt.Sprintf("(*(const %s*)_self)", cCon))
			}
			for pi, p := range im.Params {
				pn := fmt.Sprintf("_p%d", pi)
				pDecls = append(pDecls, fmt.Sprintf("%s %s", paramCType(p.Mode, p.Type), pn))
				callArgs = append(callArgs, pn)
			}

			g.line("static inline %s %s(%s) {", CType(im.Ret), wName, strings.Join(pDecls, ", "))
			if vec, isVec := vt.Concrete.(*types.Vector); isVec {
				if im.Name == "contains" {
					g.line("    return ll_vec_contains__%s(*(const %s*)_self, _p0);", vec.Mangled(), cCon)
					g.line("}")
					continue
				}
			}
			if arr, isArr := vt.Concrete.(*types.StackArray); isArr {
				if im.Name == "len" {
					g.line("    (void)_self; return (int64_t)%dLL;", arr.Size)
					g.line("}")
					continue
				}
				if im.Name == "get" {
					g.line("    return ll_arr_get__%s(*(const %s*)_self, _p0);", arr.Mangled(), cCon)
					g.line("}")
					continue
				}
				if im.Name == "contains" {
					g.line("    return ll_arr_contains__%s(*(const %s*)_self, _p0);", arr.Mangled(), cCon)
					g.line("}")
					continue
				}
			}
			if p, isP := vt.Concrete.(*types.Primitive); isP && p.Kind == types.PrimString {
				if im.Name == "len" {
					g.line("    return ((const ll_string*)_self)->len;")
					g.line("}")
					continue
				}
				if im.Name == "get" {
					optVal := im.Ret.(*types.Optional)
					g.line("    int64_t idx = _p0;")
					g.line("    const ll_string* s = (const ll_string*)_self;")
					g.line("    if (idx < 0 || idx >= s->len) return %s;", optNoneC(optVal))
					g.line("    return %s;", optSomeC(optVal, "(uint8_t)s->data[idx]"))
					g.line("}")
					continue
				}
			}
			fi := vt.Methods[idx]
			targetFn := ""
			if fi != nil {
				targetFn = fi.CName
			} else if im.Name == "to_string" {
				targetFn = g.toStrFn(vt.Concrete)
			}
			if im.Ret.Equals(types.TypeVoid) {
				g.line("    %s(%s);", targetFn, strings.Join(callArgs, ", "))
			} else {
				g.line("    return %s(%s);", targetFn, strings.Join(callArgs, ", "))
			}
			g.line("}")
		}

		// const vtable instance
		if g.unitMode == UnitLinkMain {
			g.line("const %s %s = {", vtTy, vtInst)
		} else {
			g.line("static const %s %s = {", vtTy, vtInst)
		}
		g.line("    .drop_box = %s,", dropName)
		g.line("    .clone_box = %s,", cloneName)
		for _, mp := range mPtrNames {
			g.line("    %s,", mp)
		}
		g.line("};")
	}
	g.line("")
}

