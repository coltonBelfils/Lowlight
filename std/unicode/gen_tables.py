#!/usr/bin/env python3
"""Generates std/unicode/tables.ll from the Unicode Character Database bundled with Python.

Run from the repository root after upgrading Python to pick up a new Unicode version:

    python3 std/unicode/gen_tables.py > std/unicode/tables.ll

The tables hold the full (multi-character) upper, lower, and case-fold mappings, plus the
Cased and Case_Ignorable properties needed for the Final_Sigma rule. They are derived from
str.upper(), str.lower(), and str.casefold(), which implement the Unicode default (language-
independent) case operations.
"""
import sys
import unicodedata

MAX = 0x110000


def chars():
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp, chr(cp)


def mapping(fn):
    """Returns (simple: {cp: target}, special: {cp: [cps]}) for a case function."""
    simple, special = {}, {}
    for cp, c in chars():
        m = fn(c)
        if m == c:
            continue
        if len(m) == 1:
            simple[cp] = ord(m)
        else:
            special[cp] = [ord(x) for x in m]
    return simple, special


def lower_no_context(c):
    # str.lower() applies Final_Sigma using context; a lone character has none, so U+03A3 maps
    # to U+03C3 here and the runtime applies the rule.
    return c.lower()


def ranges(simple):
    """Compresses {cp: target} into (start, end, delta, stride) runs, stride 1 or 2."""
    out = []
    cps = sorted(simple)
    i = 0
    while i < len(cps):
        start = cps[i]
        delta = simple[start] - start
        stride = 1
        end = start
        j = i + 1
        if j < len(cps) and simple[cps[j]] - cps[j] == delta and cps[j] - start in (1, 2):
            stride = cps[j] - start
            while j < len(cps) and cps[j] == end + stride and simple[cps[j]] - cps[j] == delta:
                end = cps[j]
                j += 1
        else:
            j = i + 1
        out.append((start, end, delta, stride))
        i = j
    return out


def prop_ranges(pred):
    out = []
    start = None
    prev = None
    for cp in range(MAX):
        ok = not (0xD800 <= cp <= 0xDFFF) and pred(chr(cp))
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


# Final_Sigma needs Cased and Case_Ignorable. Derive them from str.lower()'s own handling of
# U+03A3 so the runtime matches Python exactly:
#   (c + "Σ").lower() ends in "ς"        iff c is cased and not case-ignorable;
#   ("A" + c + "Σ").lower() ends in "ς"  iff c is case-ignorable, or cased.
def cased(c):
    return (c + "Σ").lower().endswith("ς")


def case_ignorable(c):
    return ("A" + c + "Σ").lower().endswith("ς") and not cased(c)


def emit_ints(name, doc, values, per_line=8):
    print(f"// {doc}")
    print(f"bind {name}: [int] = [")
    for k in range(0, len(values), per_line):
        print("\t" + ", ".join(str(v) for v in values[k:k + per_line]) + ",")
    print("]")
    print()


def emit_special(prefix, doc, special):
    keys = sorted(special)
    emit_ints(f"_{prefix}_SPECIAL_KEYS", f"{doc}: code points whose mapping is several characters.", keys)
    print(f"// {doc}: the mapping of each key above, in the same order.")
    print(f"bind _{prefix}_SPECIAL_VALUES: [string] = [")
    for k in keys:
        text = "".join("\\u{%X}" % cp for cp in special[k])
        print(f'\t"{text}",')
    print("]")
    print()


def emit_map(prefix, doc, fn):
    simple, special = mapping(fn)
    flat = []
    for r in ranges(simple):
        flat.extend(r)
    emit_ints(f"_{prefix}_RANGES", f"{doc}: one-to-one mappings as (start, end, delta, stride) runs, sorted by start.", flat, per_line=8)
    emit_special(prefix, doc, special)
    return len(simple), len(special), len(flat) // 4


print("// std/unicode tables — GENERATED by std/unicode/gen_tables.py; DO NOT EDIT.")
print(f"// Unicode {unicodedata.unidata_version}.")
print()
print(f'// The Unicode version of the case tables in this package.')
print(f'bind UNICODE_VERSION = "{unicodedata.unidata_version}"')
print()
stats = []
stats.append(("upper",) + emit_map("UPPER", "Uppercase mapping", str.upper))
stats.append(("lower",) + emit_map("LOWER", "Lowercase mapping", lower_no_context))
stats.append(("fold",) + emit_map("FOLD", "Case folding", str.casefold))
flat = [v for r in prop_ranges(cased) for v in r]
emit_ints("_CASED_RANGES", "Cased characters (for Final_Sigma), as inclusive (start, end) pairs.", flat)
flat2 = [v for r in prop_ranges(case_ignorable) for v in r]
emit_ints("_CASE_IGNORABLE_RANGES", "Case-ignorable characters (for Final_Sigma), as inclusive (start, end) pairs.", flat2)
print("stats:", stats, len(flat) // 2, len(flat2) // 2, file=sys.stderr)
